import { readFile, writeFile, mkdir, cp, rm } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
const root = fileURLToPath(new URL('../', import.meta.url)), out = resolve(root, 'dist/nixie-clock');
await mkdir(resolve(root, 'dist'), { recursive: true });
await rm(out, { recursive: true, force: true }); await mkdir(out);
for (const name of ['tool.js', 'reminders.js', 'manifest.json', 'host.js']) await cp(resolve(root, 'plugin', name), resolve(out, name));
await cp(resolve(root, 'prototype/assets'), resolve(out, 'assets'), { recursive: true });
let html = await readFile(resolve(root, 'prototype/index.html'), 'utf8');
html = html.replace('辉光管时钟 · 交互原型', '辉光管时钟').replace('<body>', '<body class="native">');
html = html.replace(/  <div id="pet">[^\n]+\n/, '').replace(/  <div id="demo">[\s\S]*?<\/div>\n<\/div>/, '</div>');
html = html.replace('<script src="assets/layout.js">', '<script src="host.js"></script>\n<script src="assets/layout.js">');
await writeFile(resolve(out, 'panel.html'), html);
const zip = resolve(root, 'dist/nixie-clock-0.2.0.zip');
await rm(zip, { force: true });
const result = spawnSync('/usr/bin/zip', ['-qr', zip, '.'], { cwd: out, stdio: 'inherit' });
if (result.status !== 0) throw new Error('Plugin ZIP failed');
await writeFile(zip + '.sha256', createHash('sha256').update(await readFile(zip)).digest('hex') + '  nixie-clock-0.2.0.zip\n');
console.log(out);
